CREATE TABLE specializations (
  id INT AUTO_INCREMENT PRIMARY KEY,
  specName VARCHAR(255) NOT NULL,
  years TINYINT NOT NULL
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE applicants (
  id INT AUTO_INCREMENT PRIMARY KEY,
  fullname VARCHAR(255) NOT NULL,
  school VARCHAR(255) NOT NULL,
  isDorm BOOLEAN NOT NULL,
  isLastYear BOOLEAN NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) DEFAULT CHARSET=utf8mb4;

CREATE TABLE specApps (
  appId INT NOT NULL,
  specId INT NOT NULL,
  PRIMARY KEY (appId, specId),
  FOREIGN KEY (appId) REFERENCES applicants(id) ON DELETE CASCADE,
  FOREIGN KEY (specId) REFERENCES specializations(id) ON DELETE CASCADE
) DEFAULT CHARSET=utf8mb4;
